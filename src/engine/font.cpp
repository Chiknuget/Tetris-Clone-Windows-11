namespace font {

    void draw_char(Canvas& canvas, int x, int y, char ch, Color c, int scale) {
        const std::uint8_t* rows = find_glyph(ch);
        if (rows == nullptr) return;
        for (int row = 0; row < kGlyphH; ++row) {
            for (int col = 0; col < kGlyphW; ++col) {
                if (rows[row] & (0x10 >> col)) {
                    canvas.fill_rect(x + col * scale, y + row * scale, scale, scale, c);
                }
            }
        }
    }

    void draw_text(Canvas& canvas, int x, int y, std::string_view text, Color c, int scale) {
        int cx = x;
        for (char ch : text) {
            draw_char(canvas, cx, y, ch, c, scale);
            cx += kAdvance * scale;
        }
    }

    int text_width(std::string_view text, int scale) {
        if (text.empty()) return 0;
        return static_cast<int>(text.size()) * kAdvance * scale - scale;
    }

}  // namespace font
