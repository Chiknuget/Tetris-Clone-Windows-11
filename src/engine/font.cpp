    const std::uint8_t* find_glyph(char ch) {
        if (ch >= 'a' && ch <= 'z') {
            ch = static_cast<char>(ch - 'a' + 'A');
        }
        for (const Glyph& g : kFont) {
            if (g.ch == ch) return g.rows;
        }
        return nullptr;
    }

